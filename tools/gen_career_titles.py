"""Dev-only: build src/llamafone/career_titles.py (career title hash ->
English text), so the mod can name a sim's job ("Adept Attorney") with a
plain dict lookup and never reads game files at runtime.

1. Install the dev-only script (python tools/dev/make_dev_mod.py), then in
   game run the cheat:  llama.dev_career_titles
   (writes Documents/Llamafone_CareerTitleRefs.json: every career level's
   title hash, from the game's own loaded tuning, all installed packs).
   Remove Mods/llamafone_dev_titles.ts4script afterwards.
2. Run:  python tools/gen_career_titles.py ["C:/path/to/The Sims 4"]
   (looks the hashes up in the English string files, writes the module)

Re-run both after new packs come out, and commit career_titles.py.
"""
import glob
import json
import os
import struct
import sys
import zlib

ROOT = sys.argv[1] if len(sys.argv) > 1 else r"C:\Program Files (x86)\Origin Games\The Sims 4"
REFS = os.path.join(os.path.expanduser("~"), "Documents", "Llamafone_CareerTitleRefs.json")
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "llamafone", "career_titles.py")
STBL = 0x220557DA


def refpack(data):
    flags = data[0]
    i = 2 + (4 if flags & 0x80 else 3)
    out_len = int.from_bytes(data[2:i], "big")
    out = bytearray()
    while i < len(data):
        b0 = data[i]
        if b0 < 0x80:
            b1 = data[i + 1]; i += 2
            plain = b0 & 3; cnt = ((b0 & 0x1C) >> 2) + 3; off = ((b0 & 0x60) << 3) + b1 + 1
        elif b0 < 0xC0:
            b1, b2 = data[i + 1], data[i + 2]; i += 3
            plain = (b1 & 0xC0) >> 6; cnt = (b0 & 0x3F) + 4; off = ((b1 & 0x3F) << 8) + b2 + 1
        elif b0 < 0xE0:
            b1, b2, b3 = data[i + 1], data[i + 2], data[i + 3]; i += 4
            plain = b0 & 3; cnt = ((b0 & 0x0C) << 6) + b3 + 5; off = ((b0 & 0x10) << 12) + (b1 << 8) + b2 + 1
        elif b0 < 0xFC:
            i += 1; plain = ((b0 & 0x1F) << 2) + 4; cnt = 0; off = 0
        else:
            i += 1; plain = b0 & 3; cnt = 0; off = 0
        out += data[i:i + plain]; i += plain
        for _ in range(cnt):
            out.append(out[-off])
        if b0 >= 0xFC:
            break
    return bytes(out[:out_len])


def stbl_strings(path):
    d = open(path, "rb").read()
    if d[:4] != b"DBPF":
        return
    count = struct.unpack_from("<I", d, 36)[0]
    pos = struct.unpack_from("<Q", d, 64)[0] or struct.unpack_from("<I", d, 40)[0]
    flags = struct.unpack_from("<I", d, pos)[0]; pos += 4
    const = []
    for b in range(8):
        if flags & (1 << b):
            const.append(struct.unpack_from("<I", d, pos)[0]); pos += 4
        else:
            const.append(None)
    for _ in range(count):
        f = []
        for b in range(8):
            if const[b] is not None:
                f.append(const[b])
            else:
                f.append(struct.unpack_from("<I", d, pos)[0]); pos += 4
        if f[0] != STBL:
            continue
        raw = d[f[4]:f[4] + (f[5] & 0x7FFFFFFF)]
        ctype = f[7] & 0xFFFF
        data = zlib.decompress(raw) if ctype == 0x5A42 else (refpack(raw) if ctype in (0xFFFF, 0xFFFE) else raw)
        if data[:4] != b"STBL":
            continue
        n = struct.unpack_from("<I", data, 7)[0]
        p = 21
        for _ in range(n):
            key, _fl, ln = struct.unpack_from("<IBH", data, p); p += 7
            yield key, data[p:p + ln].decode("utf-8", "replace")
            p += ln


def main():
    refs = json.load(open(REFS, encoding="utf-8"))
    hashes = {int(r["hash"], 16) for r in refs if r.get("hash") and r["hash"] != "00000000"}
    print(f"{len(refs)} career levels, {len(hashes)} distinct title hashes (from {REFS})")
    texts = {}
    files = sorted(glob.glob(os.path.join(ROOT, "**", "Strings_ENG_US.package"), recursive=True),
                   key=lambda p: (os.sep + "Delta" + os.sep) in p)   # patches last, so they win
    for path in files:
        for key, text in stbl_strings(path):
            if key in hashes:
                texts[key] = text
    missing = sorted(hashes - set(texts))
    print(f"{len(texts)} titles with English text, {len(missing)} without")
    lines = ['"""Career level titles (title hash -> English text). Generated by',
             'tools/gen_career_titles.py from the game\'s own tuning and string files;',
             'do not edit by hand."""', "", "TITLES = {"]
    for k in sorted(texts):
        lines.append(f"    0x{k:08X}: {texts[k]!r},")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.normpath(OUT)} ({os.path.getsize(OUT):,} bytes)")
    if 0x26D8B23E in texts:
        print("  check: 0x26D8B23E =", texts[0x26D8B23E])


if __name__ == "__main__":
    main()
